    fun askAssistant(userQuery: String) {
        if (userQuery.isBlank()) return
        val userMsg = AssistantMessage(
            id = System.currentTimeMillis().toString(),
            isUser = true,
            text = userQuery
        )
        _chatMessages.value = _chatMessages.value + userMsg

        // Smart Knowledge match or scholarly grounded response
        val matchedFaq = assistantFaqs.firstOrNull { faq ->
            userQuery.split(" ").any { word -> word.length > 2 && faq.question.contains(word) }
        }

        val responseText: String
        val evidence: List<String>
        val grade: String

        if (matchedFaq != null) {
            responseText = matchedFaq.answer
            evidence = listOf(matchedFaq.quranEvidence, matchedFaq.hadithEvidence)
            grade = "صحيح معتمد"
        } else {
            responseText = "أخي الكريم/أختي الكريمة: فيما يخص مسألتكم: «$userQuery»:\nالحمد لله والصلاة والسلام على رسول الله. الأصل في ديننا الحنيف التيسير والرجوع إلى نصوص الكتاب والسنة بفهم سلف الأمة وعلمائها المعتبرين. نوصيك بالحرص على الطهارة وإخلاص النية في القول والعمل.\n(ملاحظة: المسائل الشخصية الشائكة أو قضايا الطلاق والنزاعات المالية تتطلب مراجعة دائرة الإفتاء الرسمية أو عالم موثوق ومشافهته بالتفاصيل)."
            evidence = listOf(
                "﴿وَمَا آتَاكُمُ الرَّسُولُ فَخُذُوهُ وَمَا نَهَاكُمْ عَنْهُ فَانتَهُوا﴾ [الحشر: 7]",
                "حديث النبي ﷺ: «طلب العلم فريضة على كل مسلم» (سنن ابن ماجه)"
            )
            grade = "أصل شرعي متفق عليه"
        }

        val botMsg = AssistantMessage(
            id = (System.currentTimeMillis() + 1).toString(),
            isUser = false,
            text = responseText,
            evidenceList = evidence,
            hadithGrade = grade,
            requiresMuftiDisclaimer = true
        )
        _chatMessages.value = _chatMessages.value + botMsg
    }

