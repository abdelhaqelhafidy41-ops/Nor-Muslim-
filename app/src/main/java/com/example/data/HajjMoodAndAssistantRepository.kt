    fun startRitual(type: LapRitualType) {
        _lapState.value = LapCounterState(
            type = type,
            currentLap = 1,
            isFinished = false,
            activeDua = tawafDuas[0]
        )
    }

    fun nextLap() {
        val s = _lapState.value
        if (s.isFinished) return
        if (s.currentLap < 7) {
            val next = s.currentLap + 1
            _lapState.value = s.copy(
                currentLap = next,
                activeDua = tawafDuas.getOrElse(next - 1) { tawafDuas[0] }
            )
        } else {
            _lapState.value = s.copy(isFinished = true)
        }
    }

    fun undoLap() {
        val s = _lapState.value
        if (s.currentLap > 1) {
            val prev = s.currentLap - 1
            _lapState.value = s.copy(
                currentLap = prev,
                isFinished = false,
                activeDua = tawafDuas.getOrElse(prev - 1) { tawafDuas[0] }
            )
        }
    }

